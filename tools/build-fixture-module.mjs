/**
 * Emits the fixture vault as an ES module the page can import.
 *
 * The page is served by a scheme that hands out only static files from public/,
 * with no filesystem and no network, so the fixture bytes have to arrive as code.
 * These are the same bytes the tests read from disk — the page parses them with
 * the same parser, so what you see is the real pipeline, not a display mock.
 */
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative, sep, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readGitState } from './gitState.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const fixtureRoot = join(here, '..', 'fixtures');
const out = join(here, '..', 'public', 'build', 'fixtureVault.js');
const generatedRoot = join(here, '..', 'src', 'browser', 'generated');

const readVault = (root) => {
  const files = {};
  const walk = (dir) => {
    for (const entry of readdirSync(dir).sort()) {
      const full = join(dir, entry);
      if (statSync(full).isDirectory()) walk(full);
      else files[relative(root, full).split(sep).join('/')] = readFileSync(full, 'utf8');
    }
  };
  walk(root);
  return files;
};

// Every fixture vault ships, not just the preferred-layout one: the legacy vault is
// what proves compatibility, and a build that quietly omitted it would let the page
// claim coverage the bytes do not support.
const vaults = {};
for (const name of readdirSync(fixtureRoot).sort()) {
  if (statSync(join(fixtureRoot, name)).isDirectory()) vaults[name] = readVault(join(fixtureRoot, name));
}

mkdirSync(dirname(out), { recursive: true });
mkdirSync(generatedRoot, { recursive: true });
const fixtureJson = JSON.stringify(vaults, null, 2);
const fixtureHash = createHash('sha256').update(fixtureJson).digest('hex');
const lockfileHash = createHash('sha256')
  .update(readFileSync(join(here, '..', 'package-lock.json')))
  .digest('hex');
const packageJson = JSON.parse(readFileSync(join(here, '..', 'package.json'), 'utf8'));
const gitState = readGitState(join(here, '..'));
const buildIdentity = {
  proximaVersion: packageJson.version,
  /** The exact commit, for machines. */
  gitSha: gitState.sha,
  /** Whether those bytes are what was actually built. */
  gitTreeState: gitState.treeState,
  /** Files differing from the commit when this was built; 0 when clean. */
  gitDirtyFileCount: gitState.dirtyFileCount,
  /** The quotable provenance: the SHA, suffixed `-dirty` when the tree was modified. */
  gitDescribe: gitState.describe,
  buildMode: 'fixture',
  domainSchemaVersion: '1',
  controlSchemaVersion: '0',
  fixtureSchemaVersion: '1',
  fixtureHash,
  lockfileHash,
  fixedClock: '2026-09-06T12:00:00.000Z',
};

writeFileSync(
  join(generatedRoot, 'fixtureVault.generated.ts'),
  [
    '// Generated by tools/build-fixture-module.mjs — do not edit.',
    `export const FIXTURE_VAULTS = ${fixtureJson} as const;`,
    '',
  ].join('\n'),
  'utf8',
);
writeFileSync(
  join(generatedRoot, 'buildIdentity.generated.ts'),
  [
    '// Generated by tools/build-fixture-module.mjs — do not edit.',
    `export const BUILD_IDENTITY = ${JSON.stringify(buildIdentity, null, 2)} as const;`,
    '',
  ].join('\n'),
  'utf8',
);
writeFileSync(
  out,
  [
    '// Generated by tools/build-fixture-module.mjs — do not edit.',
    `export const FIXTURE_VAULTS = ${fixtureJson};`,
    'export const FIXTURE_VAULT = FIXTURE_VAULTS["vault-basic"];',
    '',
  ].join('\n'),
  'utf8',
);
for (const [name, files] of Object.entries(vaults)) {
  console.log(`fixture module: ${name} — ${Object.keys(files).length} files`);
}
