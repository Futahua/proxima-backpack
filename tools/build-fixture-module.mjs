/**
 * Emits the fixture vault as an ES module the page can import.
 *
 * The page is served by a scheme that hands out only static files from public/,
 * with no filesystem and no network, so the fixture bytes have to arrive as code.
 * These are the same bytes the tests read from disk — the page parses them with
 * the same parser, so what you see is the real pipeline, not a display mock.
 */
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, relative, sep, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const fixtureRoot = join(here, '..', 'fixtures');
const out = join(here, '..', 'public', 'build', 'fixtureVault.js');

const readVault = (root) => {
  const files = {};
  const walk = (dir) => {
    for (const entry of readdirSync(dir).sort()) {
      const full = join(dir, entry);
      if (statSync(full).isDirectory()) walk(full);
      else files[relative(root, full).split(sep).join('/')] = readFileSync(full, 'utf8');
    }
  };
  walk(root);
  return files;
};

// Every fixture vault ships, not just the preferred-layout one: the legacy vault is
// what proves compatibility, and a build that quietly omitted it would let the page
// claim coverage the bytes do not support.
const vaults = {};
for (const name of readdirSync(fixtureRoot).sort()) {
  if (statSync(join(fixtureRoot, name)).isDirectory()) vaults[name] = readVault(join(fixtureRoot, name));
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  [
    '// Generated by tools/build-fixture-module.mjs — do not edit.',
    `export const FIXTURE_VAULTS = ${JSON.stringify(vaults, null, 2)};`,
    'export const FIXTURE_VAULT = FIXTURE_VAULTS["vault-basic"];',
    '',
  ].join('\n'),
  'utf8',
);
for (const [name, files] of Object.entries(vaults)) {
  console.log(`fixture module: ${name} — ${Object.keys(files).length} files`);
}
